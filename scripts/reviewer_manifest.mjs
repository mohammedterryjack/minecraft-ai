import { readFileSync } from 'fs';
import { gunzipSync } from 'zlib';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { Voyager } = await import('../src/agent/voyager.js');
const reg = require('minecraft-data')('1.20.4');
const skills = JSON.parse(gunzipSync(readFileSync(new URL('../test/fixtures/icefox-live-index.json.gz', import.meta.url))));
const out = {};
for (const s of skills) for (const h of Voyager.copiedInventoryHits(s, reg)) (out[s.name] ||= []).push(`${h.where}:${h.item}${h.op}${h.n}`);
console.log(skills.length, 'skills;', Object.keys(out).length, 'skills hit;', Object.values(out).flat().length, 'hits');
for (const [k, v] of Object.entries(out)) console.log(k, v.join(' '));
